#!/usr/bin/env node
import { build } from 'esbuild';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const SCRIPT_DIR = dirname(fileURLToPath(import.meta.url));
const PROJECT_ROOT = resolve(SCRIPT_DIR, '..');
const ENGINE_ROOT = resolve(PROJECT_ROOT, 'engine-src');
const ENTRY_POINT = resolve(ENGINE_ROOT, 'packages/core/src/browser-entry.ts');
const OUTPUT_FILE = resolve(PROJECT_ROOT, 'js/engine.browser.js');
const REQUIRE_SHIM = resolve(SCRIPT_DIR, 'lib/esbuild-require-shim.js');

const ALIAS_MAP = {
  '@diagrammender/types': resolve(ENGINE_ROOT, 'packages/types/src/index.ts'),
  '@diagrammender/analyzers': resolve(ENGINE_ROOT, 'packages/analyzers/src/index.ts'),
  '@diagrammender/emitters-mermaid': resolve(ENGINE_ROOT, 'packages/emitters/mermaid/src/index.ts'),
  '@diagrammender/fix-rules-mermaid-compat': resolve(ENGINE_ROOT, 'packages/fix-rules/mermaid-compat/src/index.ts'),
  '@diagrammender/parsers-python': resolve(ENGINE_ROOT, 'packages/parsers/python/src/index.ts'),
  'node:path': resolve(SCRIPT_DIR, 'lib/path-browser-shim.js'),
};

const aliasPlugin = {
  name: 'diagrammender-alias',
  setup(buildContext) {
    buildContext.onResolve({ filter: /.*/ }, (args) => {
      const replacement = ALIAS_MAP[args.path];
      if (replacement) {
        return { path: replacement };
      }
      return;
    });
  },
};

async function main() {
  try {
    await build({
      entryPoints: [ENTRY_POINT],
      outfile: OUTPUT_FILE,
      bundle: true,
      format: 'iife',
      platform: 'browser',
      target: ['es2020'],
      sourcemap: false,
      minify: false,
      logLevel: 'info',
      banner: {
        js: '// Auto-generated by scripts/build-engine-browser.mjs\n',
      },
      inject: [REQUIRE_SHIM],
      plugins: [aliasPlugin],
      define: {
        'process.env.NODE_ENV': '"production"',
      },
    });
    console.log(`Built browser engine bundle -> ${OUTPUT_FILE}`);
  } catch (error) {
    console.error('Failed to build browser engine bundle:', error?.message || error);
    process.exit(1);
  }
}

await main();
